  # Preserve model overrides and upload server-only AI/Meta configuration.
  # Empty local values must not erase secrets already configured on Railway.
  $optionalServerVariables = @('GEMINI_API_KEY','GEMINI_TEMPLATE_MODEL','META_PLATFORM_APP_ID','META_PLATFORM_APP_SECRET','META_EMBEDDED_SIGNUP_CONFIG_ID','META_GRAPH_API_VERSION')
