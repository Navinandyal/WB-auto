#!/usr/bin/env python3
"""Configure the checked-in iOS project without replacing application source."""
import argparse
import base64
import json
import plistlib
import re
import sys
from pathlib import Path
from urllib.parse import urlsplit

MOBILE = Path(__file__).resolve().parents[1]
IOS = MOBILE / 'ios'
CONFIG = MOBILE / 'ios_build_config.json'
BUNDLE_PATTERN = r'[A-Za-z][A-Za-z0-9-]*(?:\.[A-Za-z][A-Za-z0-9-]*)+'


def validate_url(value, local_development=False):
    url = urlsplit(value)
    if url.scheme not in ('https', 'http') or not url.hostname or url.username or url.password or url.query or url.fragment:
        raise ValueError('Use a backend origin such as https://api.example.com, without credentials, query or fragment.')
    if url.path not in ('', '/'):
        raise ValueError('Use the backend origin without /api or another path.')
    try:
        port = url.port
    except ValueError:
        raise ValueError('Backend port is invalid.')
    if port is not None and not 1 <= port <= 65535:
        raise ValueError('Backend port is invalid.')
    if url.scheme == 'http' and not local_development:
        raise ValueError('HTTPS is required. HTTP is allowed only with --local-development for Debug runs.')
    if '\n' in value or '\r' in value or any(c.isspace() for c in value):
        raise ValueError('Backend URL must not contain whitespace.')
    return value.rstrip('/')


def configure(api_url, bundle_id, team_id='', push=False, local_development=False, mobile=MOBILE):
    api_url = validate_url(api_url, local_development)
    if len(bundle_id) > 255 or not re.fullmatch(BUNDLE_PATTERN, bundle_id):
        raise ValueError('Bundle ID must use reverse-domain notation, for example com.aikyam.whatsappautomation.')
    if team_id and not re.fullmatch(r'[A-Z0-9]{10}', team_id):
        raise ValueError('Apple Team ID must be 10 uppercase letters/digits; leave it blank for simulator setup.')
    ios = mobile / 'ios'
    firebase = ios / 'Runner/GoogleService-Info.plist'
    if push:
        if not team_id:
            raise ValueError('Push signing requires your Apple Developer Team ID. Omit --push for a basic run.')
        if not firebase.is_file():
            raise ValueError('Place your iOS GoogleService-Info.plist in mobile/ios/Runner before enabling --push.')
        data = plistlib.loads(firebase.read_bytes())
        if data.get('BUNDLE_ID') != bundle_id:
            raise ValueError('GoogleService-Info.plist BUNDLE_ID does not match the configured bundle ID.')
        if ':ios:' not in data.get('GOOGLE_APP_ID', '') or not all(data.get(k) for k in ['API_KEY', 'PROJECT_ID', 'GCM_SENDER_ID']):
            raise ValueError('Use a genuine Firebase iOS app configuration, not the Android Firebase file.')
    definitions = base64.b64encode(('API_BASE_URL=' + api_url).encode()).decode()
    settings = {'apiUrl': api_url, 'bundleId': bundle_id, 'teamId': team_id,
                'push': push, 'localDevelopment': local_development}
    # Flutter CLI and direct Xcode Run use the same backend definition.
    text = ('// Generated by tool/ios_configure.py. Re-run PREPARE_IPHONE_MAC.command to change settings.\n'
            'GREETSYNC_BUNDLE_ID = ' + bundle_id + '\n'
            'GREETSYNC_TEAM_ID = ' + team_id + '\n'
            'GREETSYNC_PYTHON_PATH = ' + sys.executable + '\n'
            'GREETSYNC_PUSH_ENVIRONMENT = production\n'
            'GREETSYNC_ENTITLEMENTS_FILE = Runner/' + ('RunnerPush.entitlements' if push else 'Runner.entitlements') + '\n'
            'GREETSYNC_BACKEND_MODE = ' + ('local' if local_development else 'https') + '\n'
            'DART_DEFINES = $(inherited),' + definitions + '\n')
    (ios / 'Flutter/GreetSync.xcconfig').write_text(text)
    for filename in ['Info.plist', 'Info-Debug.plist']:
        path = ios / 'Runner' / filename
        data = plistlib.loads(path.read_bytes())
        data['NSAppTransportSecurity'] = {'NSAllowsLocalNetworking': True}
        if filename == 'Info-Debug.plist' and local_development:
            data['NSAppTransportSecurity']['NSAllowsArbitraryLoads'] = True
        if push:
            data['UIBackgroundModes'] = ['fetch', 'remote-notification']
        else:
            data.pop('UIBackgroundModes', None)
        path.write_bytes(plistlib.dumps(data, sort_keys=False))
    (mobile / 'ios_build_config.json').write_text(json.dumps(settings, indent=2) + '\n')
    return settings


def export_options(method, mobile=MOBILE):
    config = json.loads((mobile / 'ios_build_config.json').read_text())
    validate_url(config['apiUrl'])
    if not config['teamId']:
        raise ValueError('Set your Apple Team ID with PREPARE_IPHONE_MAC.command before exporting an IPA.')
    mapping = {'app-store': 'app-store-connect', 'ad-hoc': 'release-testing', 'development': 'debugging'}
    if method not in mapping:
        raise ValueError('IPA method must be development, ad-hoc or app-store.')
    profile_environment = 'development' if method == 'development' else 'production'
    path = mobile / 'ios/Flutter/GreetSync.xcconfig'
    text = path.read_text()
    text = re.sub(r'^GREETSYNC_PUSH_ENVIRONMENT = .*$', 'GREETSYNC_PUSH_ENVIRONMENT = ' + profile_environment, text, flags=re.M)
    path.write_text(text)
    options = {'method': mapping[method], 'teamID': config['teamId'], 'signingStyle': 'automatic',
               'destination': 'export', 'manageAppVersionAndBuildNumber': False,
               'stripSwiftSymbols': True}
    output = mobile / 'ios/ExportOptions.generated.plist'
    output.write_bytes(plistlib.dumps(options, sort_keys=False))
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest='command', required=True)
    setup = sub.add_parser('configure')
    setup.add_argument('--api-url', required=True)
    setup.add_argument('--bundle-id', default='com.aikyam.whatsappautomation')
    setup.add_argument('--team-id', default='')
    setup.add_argument('--push', action='store_true')
    setup.add_argument('--local-development', action='store_true')
    export = sub.add_parser('export-options')
    export.add_argument('--method', choices=['development', 'ad-hoc', 'app-store'], default='development')
    args = parser.parse_args()
    try:
        if args.command == 'configure':
            result = configure(args.api_url, args.bundle_id, args.team_id, args.push, args.local_development)
            print('Configured GreetSync for iOS: ' + result['bundleId'])
            print('Push notifications: ' + ('enabled' if result['push'] else 'optional / disabled'))
        else:
            print(export_options(args.method))
    except (ValueError, OSError, json.JSONDecodeError, plistlib.InvalidFileException) as error:
        parser.exit(2, 'Configuration error: ' + str(error) + '\n')

if __name__ == '__main__':
    main()
